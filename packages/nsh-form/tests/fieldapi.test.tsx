import { expect, test } from "nsh/test";
import { line, start } from "./support";

test("27. field API: array methods, getValue, setValue, getMeta, getInfo, getLinkedFields, setErrorMap and parseValueWithSchema", async () => {
  const app = await start("fieldApi");
  expect(line(app, "tags-field")).toBe("tags-field a,b");
  await app.press("role:button[Field push]");
  expect(line(app, "tags-field")).toBe("tags-field a,b,c");
  await app.press("role:button[Field insert]");
  expect(line(app, "tags-field")).toBe("tags-field x,a,b,c");
  await app.press("role:button[Field replace]");
  expect(line(app, "tags-field")).toBe("tags-field y,a,b,c");
  await app.press("role:button[Field remove]");
  expect(line(app, "tags-field")).toBe("tags-field a,b,c");
  await app.press("role:button[Field swap]");
  expect(line(app, "tags-field")).toBe("tags-field b,a,c");
  await app.press("role:button[Field move]");
  expect(line(app, "tags-field")).toBe("tags-field a,b,c");
  await app.press("role:button[Field get]");
  expect(line(app, "result ")).toBe('result [{"name":"a"},{"name":"b"},{"name":"c"}]');
  await app.press("role:button[Field set]");
  expect(line(app, "tags-field")).toBe("tags-field set");
  await app.press("role:button[Field meta]");
  expect(line(app, "result ")).toBe("result true");
  await app.press("role:button[Field info]");
  expect(line(app, "result ")).toBe("result true");
  await app.press("role:button[Field linked]");
  expect(line(app, "result ")).toBe("result 0");
  await app.press("role:button[Field error map]");
  await app.press("role:button[Field errors]");
  expect(line(app, "result ")).toContain("Field error by hand");
  await app.press("role:button[Field blur meta]");
  await app.press("role:button[Field blurred]");
  expect(line(app, "result ")).toBe("result true");
  await app.press("role:button[Field parse]");
  expect(line(app, "result ")).toBe('result [{"message":"Parse: empty"}]');
  await app.press("role:button[Field clear]");
  expect(line(app, "tags-field")).toBe("tags-field ");
  await app.press("role:button[Field validate]");
  expect(line(app, "result ")).toBe('result ["No tags"]');
});
